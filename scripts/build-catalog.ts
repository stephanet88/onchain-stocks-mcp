// Regenerates src/catalog.ts, the token list keyless mode works from. Needs TOKENS_API_KEY.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { topStocks } from "../src/tokens.ts";
import { issuerName, type CatalogToken } from "../src/tools.ts";

// below this a Jupiter quote moves on a single trade and says little
const MIN_LIQUIDITY_USD = 10_000;

const apiKey = process.env.TOKENS_API_KEY;
if (!apiKey) throw new Error("TOKENS_API_KEY is not set");

const tokens: CatalogToken[] = [];
const seen = new Set<string>();
for (const asset of await topStocks(apiKey, 100)) {
  for (const v of asset.variants ?? []) {
    const decimals = v.market?.decimals;
    if (v.kind !== "tokenized_equity" || decimals == null || (v.market?.liquidity ?? 0) < MIN_LIQUIDITY_USD || seen.has(v.mint)) continue;
    seen.add(v.mint);
    tokens.push({
      symbol: (asset.symbol ?? asset.assetId).toUpperCase(),
      name: asset.name ?? asset.symbol ?? asset.assetId,
      issuer: issuerName(v, asset.symbol),
      mint: v.mint,
      decimals,
      redeemable: v.stockVariantTier ?? null,
    });
  }
}
tokens.sort((a, b) => a.symbol.localeCompare(b.symbol) || a.issuer.localeCompare(b.issuer));

const generatedAt = new Date().toISOString().slice(0, 10);
const body = `// generated by \`npm run catalog\` from api.tokens.xyz on ${generatedAt}, do not edit
import type { Catalog } from "./tools.ts";

export const CATALOG: Catalog = ${JSON.stringify({ generatedAt, tokens }, null, 2)};
`;
writeFileSync(join(import.meta.dirname, "..", "src", "catalog.ts"), body);
console.log(`${tokens.length} tokens of ${new Set(tokens.map((t) => t.symbol)).size} stocks`);
